#!/usr/bin/env node
// Writes app/js/config.js from .env. Only the Supabase URL and *publishable* key go
// into the app. They're designed to be public; row-level security protects the data.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const env = Object.fromEntries(readFileSync(join(root, '.env'), 'utf8').split('\n')
  .filter((l) => l.includes('=')).map((l) => { const i = l.indexOf('='); return [l.slice(0, i).trim(), l.slice(i + 1).trim()]; }));

const url = (env.SUPABASE_URL || '').replace(/\/+$/, '');
const key = env.SUPABASE_KEY || '';
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) throw new Error('SUPABASE_URL looks wrong');
if (/service_role|sb_secret_/.test(key)) throw new Error('That is a secret key; use the publishable key');

writeFileSync(join(root, 'app', 'js', 'config.js'),
  `// Generated by tools/write-config.mjs. Public values; data is protected by row-level security.\n` +
  `export const SUPABASE_URL = ${JSON.stringify(url)};\nexport const SUPABASE_KEY = ${JSON.stringify(key)};\n`);
console.log('Wrote app/js/config.js for', url);
